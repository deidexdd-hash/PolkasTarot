window.Utils = (() => {
  /**
   * Случайное целое от 0 до max-1.
   *
   * Берём из crypto, когда он доступен: Math.random в браузерах не обещает
   * криптографического качества, а гадание — ровно тот случай, где
   * предсказуемость жребия обесценивает всё остальное. Хвост отбраковываем,
   * иначе деление по модулю сделало бы младшие значения чуть вероятнее.
   */
  function randomInt(max) {
    if (max <= 0) return 0;
    const c = window.crypto || window.msCrypto;
    if (c && c.getRandomValues) {
      const limit = Math.floor(0x100000000 / max) * max;
      const buf = new Uint32Array(1);
      let v;
      do {
        c.getRandomValues(buf);
        v = buf[0];
      } while (v >= limit);
      return v % max;
    }
    return Math.floor(Math.random() * max);
  }

  /**
   * Тасовка Фишера — Йетса.
   *
   * Раньше здесь стояло `[...arr].sort(() => Math.random() - 0.5)` —
   * распространённый, но неверный приём. Компаратор обязан быть
   * согласованным (если a<b и b<c, то a<c), случайный таковым не является,
   * а алгоритм сортировки на это свойство опирается. На выходе получается
   * не равномерная перестановка, а сильно перекошенная.
   *
   * Перекос был не теоретический. На 200 000 раздач «Карты дня»:
   *
   *     Шестерка Пентаклей   191% от нормы
   *     Маг                   15% от нормы
   *
   * то есть между самой частой и самой редкой картой разница почти
   * в четырнадцать раз. Хи-квадрат 28752 при 77 степенях свободы, где
   * порог значимости около 99. После замены — перекос 1.3x и хи-квадрат
   * около 77, то есть в пределах случайного разброса.
   *
   * Проверяется в tools/e2e.js: тест падает, если вернуть прежний вариант.
   */
  function shuffle(arr) {
    const a = [...arr];
    for (let i = a.length - 1; i > 0; i--) {
      const j = randomInt(i + 1);
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  }

  function formatDate(date = new Date()) {
    return date.toLocaleString('ru-RU');
  }

  return { shuffle, randomInt, formatDate };
})();
