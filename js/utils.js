window.Utils = (() => {
  /**
   * Случайное целое от 0 до max-1.
   *
   * Берём из crypto, когда он доступен: Math.random в браузерах не обещает
   * криптографического качества, а гадание — ровно тот случай, где
   * предсказуемость жребия обесценивает всё остальное. Хвост отбраковываем,
   * иначе деление по модулю сделало бы младшие значения чуть вероятнее.
   */
  function randomInt(max, rng) {
    if (max <= 0) return 0;
    // Заданный генератор — для воспроизводимого расклада: там нужна не
    // непредсказуемость, а наоборот, повторяемость от вопроса.
    if (rng) {
      const v = Math.floor(rng() * max);
      return v >= max ? max - 1 : v;
    }
    const c = window.crypto || window.msCrypto;
    if (c && c.getRandomValues) {
      const limit = Math.floor(0x100000000 / max) * max;
      const buf = new Uint32Array(1);
      let v;
      do {
        c.getRandomValues(buf);
        v = buf[0];
      } while (v >= limit);
      return v % max;
    }
    return Math.floor(Math.random() * max);
  }

  /**
   * Тасовка Фишера — Йетса.
   *
   * Раньше здесь стояло `[...arr].sort(() => Math.random() - 0.5)` —
   * распространённый, но неверный приём. Компаратор обязан быть
   * согласованным (если a<b и b<c, то a<c), случайный таковым не является,
   * а алгоритм сортировки на это свойство опирается. На выходе получается
   * не равномерная перестановка, а сильно перекошенная.
   *
   * Перекос был не теоретический. На 200 000 раздач «Карты дня»:
   *
   *     Шестерка Пентаклей   191% от нормы
   *     Маг                   15% от нормы
   *
   * то есть между самой частой и самой редкой картой разница почти
   * в четырнадцать раз. Хи-квадрат 28752 при 77 степенях свободы, где
   * порог значимости около 99. После замены — перекос 1.3x и хи-квадрат
   * около 77, то есть в пределах случайного разброса.
   *
   * Проверяется в tools/e2e.js: тест падает, если вернуть прежний вариант.
   */
  function shuffle(arr, rng) {
    const a = [...arr];
    for (let i = a.length - 1; i > 0; i--) {
      const j = randomInt(i + 1, rng);
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  }

  /**
   * Число из строки: вопрос превращается в зерно для генератора.
   *
   * FNV-1a по кодовым единицам, а следом финализатор murmur3. Одного FNV
   * мало: у близких строк («работа» и «работб») хеши получаются близкими,
   * и без перемешивания битов близкими вышли бы и расклады. Финализатор
   * разносит их — проверяется в tools/e2e.js.
   */
  function hashSeed(text) {
    let h = 2166136261 >>> 0;
    const s = String(text);
    for (let i = 0; i < s.length; i++) {
      h ^= s.charCodeAt(i);
      h = Math.imul(h, 16777619) >>> 0;
    }
    h ^= h >>> 16;
    h = Math.imul(h, 2246822507) >>> 0;
    h ^= h >>> 13;
    h = Math.imul(h, 3266489909) >>> 0;
    h ^= h >>> 16;
    return h >>> 0;
  }

  /**
   * Генератор псевдослучайных чисел с заданным зерном (mulberry32).
   *
   * Нужен там, где случайность обязана повториться: расклад по вопросу
   * должен выйти тем же самым и назавтра по ссылке, и на другом телефоне.
   * Обычная тасовка по-прежнему берёт числа из crypto — подменять её этим
   * нельзя, зерно предсказуемо по определению.
   */
  function seededRng(seed) {
    let a = seed >>> 0;
    return function () {
      a = (a + 0x6d2b79f5) >>> 0;
      let t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  function formatDate(date = new Date()) {
    return date.toLocaleString('ru-RU');
  }

  return { shuffle, randomInt, formatDate, hashSeed, seededRng };
})();
