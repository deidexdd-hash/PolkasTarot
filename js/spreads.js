// js/spreads.js - Конфигурация раскладов
//
// Расклад описывается только позициями: как называется место в раскладе и в
// какой клетке сетки оно стоит — ["Прошлое", столбец, строка]. Всё остальное
// считается отсюда: число карт, подписи, ширина сетки и области CSS.
//
// Раньше сетку писали руками (grid + areas), параллельно с ней — labels, а
// count третьим списком. Три списка приходилось держать в согласии вручную, и
// они разъезжались: в «Кресте» пустовал целый ряд, в «Кельтском кресте» —
// пятая колонка и последняя строка, из-за чего фигура была сдвинута вбок.
// Теперь такое расхождение невозможно по построению, а наложение двух карт на
// одну клетку и дырки в нумерации ловятся проверкой при загрузке.
window.Spreads = (() => {
    const definitions = {
        daily: {
            title: "Карта дня",
            description: "Простой и быстрый способ получить совет на день",
            positions: [
                ["Энергия дня", 1, 1]
            ]
        },

        threecards: {
            title: "Прошлое - Настоящее - Будущее",
            description: "Классический расклад для понимания развития ситуации",
            positions: [
                ["Прошлое", 1, 1],
                ["Настоящее", 2, 1],
                ["Будущее", 3, 1]
            ]
        },

        cross: {
            title: "Крест",
            description: "Расклад для глубокого анализа проблемы",
            positions: [
                ["Основа ситуации", 1, 2],
                ["Препятствие", 2, 1],
                ["Совет", 3, 2],
                ["Итог", 2, 2]
            ]
        },

        celtic: {
            title: "Кельтский крест",
            description: "Самый подробный расклад для комплексного анализа",
            // Классическая фигура: вертикаль «венец - ситуация - пересечение -
            // основа» по центру, слева недавнее прошлое, справа ближайшее
            // будущее, посох отдельной колонкой сверху вниз.
            positions: [
                ["Текущая ситуация", 2, 2],
                ["Пересекающее влияние", 2, 3],
                ["Основа ситуации", 2, 4],
                ["Недавнее прошлое", 1, 2],
                ["Возможное будущее", 2, 1],
                ["Ближайшее будущее", 3, 2],
                ["Ваше отношение", 4, 4],
                ["Окружение", 4, 3],
                ["Надежды и страхи", 4, 2],
                ["Итог", 4, 1]
            ]
        },

        pyramid: {
            title: "Пирамида любви",
            description: "Расклад для анализа романтических отношений",
            positions: [
                ["Вы", 1, 3],
                ["Партнер", 4, 3],
                ["Связь между вами", 2, 2],
                ["Будущее отношений", 3, 1]
            ]
        },

        choice: {
            title: "Два пути",
            description: "Помощь в принятии решения между двумя вариантами",
            positions: [
                ["Текущая ситуация", 2, 2],
                ["Путь А: Развитие", 1, 1],
                ["Путь А: Результат", 1, 2],
                ["Путь Б: Развитие", 3, 1],
                ["Путь Б: Результат", 3, 2]
            ]
        },

        year: {
            title: "Год вперед",
            description: "Прогноз на каждый месяц следующего года",
            positions: [
                ["Январь", 1, 1], ["Февраль", 2, 1], ["Март", 3, 1], ["Апрель", 4, 1],
                ["Май", 1, 2], ["Июнь", 2, 2], ["Июль", 3, 2], ["Август", 4, 2],
                ["Сентябрь", 1, 3], ["Октябрь", 2, 3], ["Ноябрь", 3, 3], ["Декабрь", 4, 3]
            ]
        },

        career: {
            title: "Карьера и финансы",
            description: "Специализированный расклад для работы и денег",
            positions: [
                ["Текущая ситуация", 2, 1],
                ["Ваши сильные стороны", 1, 2],
                ["Препятствия", 2, 2],
                ["Возможности", 3, 2],
                ["Совет", 2, 3]
            ]
        }
    };

    /**
     * Собирает из позиций то, что нужно отрисовке: сетку и области CSS.
     *
     * Бросает исключение на неверном описании — две карты в одной клетке,
     * нулевой или дробный номер, пустой список. Такое описание не даст
     * правильной картинки ни при каких условиях, и молчать об этом хуже,
     * чем упасть: ошибку видно сразу, а не через кривой расклад у гостя.
     */
    function build(key, def) {
        const pos = def.positions;
        if (!Array.isArray(pos) || pos.length === 0) {
            throw new Error('нет позиций');
        }

        let cols = 0;
        let rows = 0;
        for (const [label, col, row] of pos) {
            if (!label) throw new Error('позиция без подписи');
            if (!Number.isInteger(col) || !Number.isInteger(row) || col < 1 || row < 1) {
                throw new Error(`«${label}»: клетка ${col}:${row} вне сетки`);
            }
            if (col > cols) cols = col;
            if (row > rows) rows = row;
        }

        const cells = Array.from({ length: rows }, () => new Array(cols).fill('.'));
        pos.forEach(([label, col, row], i) => {
            const taken = cells[row - 1][col - 1];
            if (taken !== '.') {
                throw new Error(`«${label}» встаёт на занятую клетку ${col}:${row}`);
            }
            cells[row - 1][col - 1] = 'p' + (i + 1);
        });

        return {
            key,
            title: def.title,
            description: def.description,
            count: pos.length,
            labels: pos.map((p) => p[0]),
            grid: `repeat(${cols}, 1fr)`,
            areas: cells.map((row) => `'${row.join(' ')}'`)
        };
    }

    const types = {};
    const errors = [];
    for (const [key, def] of Object.entries(definitions)) {
        try {
            types[key] = build(key, def);
        } catch (e) {
            // Ломать всю страницу из-за одного кривого расклада не стоит:
            // остальные семь исправны. Но и делать вид, что всё хорошо,
            // тоже нельзя — список ошибок проверяется в tools/e2e.js.
            errors.push(`${key}: ${e.message}`);
            console.error(`Расклад «${key}» описан неверно — ${e.message}`);
        }
    }

    return {
        types,
        errors,

        /**
         * Получить конфигурацию расклада по ключу
         */
        getConfig(key) {
            return this.types[key] || null;
        },

        /**
         * Получить все доступные расклады
         */
        getAll() {
            return Object.keys(this.types).map((key) => ({ ...this.types[key] }));
        }
    };
})();
